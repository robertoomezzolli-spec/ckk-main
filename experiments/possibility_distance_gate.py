#!/usr/bin/env python3
"""Blind possibility-distance gate over the frozen CKK grammar.

No physical model is supplied. The experiment asks only whether the grammar's
OWN derivation graph contains the structural pattern

    approach an endogenous BOUNDARY -> fewer admissible continuations
                                   -> greater reciprocal accessibility.

The kernel is imported read-only. Nothing under ckk_snapshot/ is modified.
"""
from __future__ import annotations

import json
import math
import sys
from collections import defaultdict, deque
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / "ckk_snapshot" / "ckk" / "gen"
sys.path.insert(0, str(GEN))

import grammar as G  # noqa: E402
from expand import expand_structural_auditable  # noqa: E402

OUT = ROOT / "results" / "possibility_distance_gate.json"
LEVELS = 4
CAP = 30000


def rankdata(xs):
    order = sorted(range(len(xs)), key=lambda i: xs[i])
    ranks = [0.0] * len(xs)
    i = 0
    while i < len(order):
        j = i + 1
        while j < len(order) and xs[order[j]] == xs[order[i]]:
            j += 1
        r = (i + 1 + j) / 2.0
        for k in range(i, j):
            ranks[order[k]] = r
        i = j
    return ranks


def pearson(x, y):
    if len(x) < 3:
        return None
    mx, my = sum(x) / len(x), sum(y) / len(y)
    vx = sum((a - mx) ** 2 for a in x)
    vy = sum((b - my) ** 2 for b in y)
    if vx == 0 or vy == 0:
        return None
    return sum((a - mx) * (b - my) for a, b in zip(x, y)) / math.sqrt(vx * vy)


def spearman(x, y):
    return pearson(rankdata(x), rankdata(y))


def main():
    pool, derivations = expand_structural_auditable(levels=LEVELS, cap=CAP)

    # structural_sig -> Struct. This is the frozen CKK state space generated by
    # the existing grammar, not a hand-built graph.
    states = {s.structural_sig(): s for s in pool.values()}

    # Project each derivation event to directed input->output reachability. A
    # binary event contributes one reachability edge from each participating
    # input, but event identity itself remains untouched.
    adj = defaultdict(set)
    rev = defaultdict(set)
    first_seen = {s.structural_sig(): 0 for s in G.SEEDS if s.structural_sig() in states}
    for d in derivations:
        if d.output not in states:
            continue
        first_seen[d.output] = min(first_seen.get(d.output, d.level), d.level)
        for inp in d.inputs:
            if inp in states and inp != d.output:
                adj[inp].add(d.output)
                rev[d.output].add(inp)

    # IMPORTANT: boundary is not 'graph stopped here'. It is the grammar's own
    # BOUNDARY state kind emitted by op_boundary. Thus finite runner truncation
    # cannot manufacture the target boundary.
    boundaries = {k for k, s in states.items() if s.kind == G.BOUNDARY}

    # Shortest directed distance to an endogenous BOUNDARY via reverse BFS.
    dist = {}
    q = deque()
    for b in boundaries:
        dist[b] = 0
        q.append(b)
    while q:
        v = q.popleft()
        for u in rev.get(v, ()):
            nd = dist[v] + 1
            if u not in dist or nd < dist[u]:
                dist[u] = nd
                q.append(u)

    # Exclude the newest generated frontier. Its outdegree is artificially low
    # because the finite audit did not get another expansion round.
    eligible = {
        n for n in states
        if n in dist and first_seen.get(n, LEVELS) <= LEVELS - 1
    }

    accessibility = {n: len(adj.get(n, ())) for n in eligible}
    resistance = {
        n: (math.inf if accessibility[n] == 0 else 1.0 / accessibility[n])
        for n in eligible
    }

    # We do not call A=0 a number. Operationally it means there is no observed
    # admissible continuation in this generated state space, represented by inf.
    zero_A = [n for n in eligible if accessibility[n] == 0]

    finite_nodes = [n for n in eligible if accessibility[n] > 0]
    dvals = [dist[n] for n in finite_nodes]
    avals = [accessibility[n] for n in finite_nodes]
    rvals = [resistance[n] for n in finite_nodes]

    rho_d_a = spearman(dvals, avals) if finite_nodes else None
    rho_d_r = spearman(dvals, rvals) if finite_nodes else None

    approach = []
    nonincrease_A = nondecrease_R = strict_R = 0
    for s in eligible:
        for t in adj.get(s, ()):
            if t not in eligible:
                continue
            if dist[t] == dist[s] - 1:
                approach.append((s, t))
                if accessibility[t] <= accessibility[s]:
                    nonincrease_A += 1
                if resistance[t] >= resistance[s]:
                    nondecrease_R += 1
                if resistance[t] > resistance[s]:
                    strict_R += 1

    other = []
    for s in eligible:
        for t in adj.get(s, ()):
            if t in eligible and dist[t] != dist[s] - 1:
                other.append((s, t))

    n_app = len(approach)
    frac_A = nonincrease_A / n_app if n_app else None
    frac_R = nondecrease_R / n_app if n_app else None
    frac_strict = strict_R / n_app if n_app else None
    other_frac_R = (
        sum(1 for s, t in other if resistance[t] >= resistance[s]) / len(other)
        if other else None
    )
    contrast = (
        frac_R - other_frac_R
        if frac_R is not None and other_frac_R is not None else None
    )

    # Distance-binned descriptive profile. This is useful regardless of gate.
    bins = {}
    for d in sorted(set(dist[n] for n in eligible)):
        ns = [n for n in eligible if dist[n] == d]
        vals = [accessibility[n] for n in ns]
        bins[str(d)] = {
            "states": len(ns),
            "mean_accessibility": sum(vals) / len(vals) if vals else None,
            "min_accessibility": min(vals) if vals else None,
            "max_accessibility": max(vals) if vals else None,
            "zero_accessibility": sum(v == 0 for v in vals),
        }

    enough = len(eligible) >= 20 and len(boundaries) > 0 and n_app >= 20
    ratchet = bool(
        enough and frac_R is not None and frac_R >= 0.75
        and frac_strict is not None and frac_strict >= 0.25
    )
    discriminates = bool(contrast is not None and contrast >= 0.10)

    if ratchet and discriminates:
        status = "ENDOGENOUS_POSSIBILITY_RESISTANCE_CANDIDATE"
    elif enough:
        status = "POSSIBILITY_GRAPH_PRESENT_NO_BOUNDARY_RATCHET"
    else:
        status = "INSUFFICIENT_GENERATED_PROVENANCE"

    result = {
        "schema": "ckk.external.possibility-distance-gate.v2",
        "status": status,
        "kernel_modified": False,
        "generator": {
            "function": "expand_structural_auditable",
            "levels": LEVELS,
            "cap": CAP,
            "states": len(states),
            "derivation_events": len(derivations),
            "endogenous_boundary_states": len(boundaries),
            "eligible_nonfrontier_states_reaching_boundary": len(eligible),
        },
        "frozen_definitions": {
            "boundary": "CKK state with kind == BOUNDARY; never finite-run terminal",
            "accessibility": "A(v)=count of distinct generated successor states",
            "operational_resistance": "R(v)=1/A(v); A=0 represented operationally as +infinity/unreachable",
            "approach": "directed edge lowering shortest graph distance to an endogenous BOUNDARY by one",
            "frontier_guard": "states first generated in final expansion level are excluded",
        },
        "tests": {
            "zero_accessibility_states": len(zero_A),
            "approach_edges": n_app,
            "approach_accessibility_nonincrease_fraction": frac_A,
            "approach_resistance_nondecrease_fraction": frac_R,
            "approach_resistance_strict_increase_fraction": frac_strict,
            "other_edges_resistance_nondecrease_fraction": other_frac_R,
            "approach_vs_other_contrast": contrast,
            "spearman_distance_vs_accessibility": rho_d_a,
            "spearman_distance_vs_resistance": rho_d_r,
            "boundary_ratchet": ratchet,
            "approach_specific_discrimination": discriminates,
        },
        "distance_profile": bins,
        "interpretation": (
            "This is a structural CKK test only. A positive result would identify an endogenous "
            "possibility/accessibility ratchet in the frozen derivation architecture; it would not by "
            "itself derive gravity, spacetime curvature, or any physical force law."
        ),
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
    print(json.dumps(result, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
